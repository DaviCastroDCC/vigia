-- Um incidente começa depois de N falhas seguidas e termina na primeira verificação bem-sucedida.
CREATE TABLE incidents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id  BIGINT                   NOT NULL REFERENCES monitored_services (id) ON DELETE CASCADE,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    cause       VARCHAR(500)
);

CREATE INDEX idx_incidents_service_time ON incidents (service_id, started_at DESC);

ALTER TABLE monitored_services ADD COLUMN consecutive_failures INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE monitored_services ADD COLUMN failing_since TIMESTAMP WITH TIME ZONE;

