CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)             NOT NULL,
    email         VARCHAR(150)             NOT NULL UNIQUE,
    password_hash VARCHAR(100)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE monitored_services (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id         BIGINT                   NOT NULL REFERENCES users (id),
    name             VARCHAR(100)             NOT NULL,
    url              VARCHAR(500)             NOT NULL,
    interval_seconds INTEGER                  NOT NULL,
    active           BOOLEAN                  NOT NULL,
    last_status      VARCHAR(10),
    last_checked_at  TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_services_owner ON monitored_services (owner_id);

CREATE TABLE health_checks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id       BIGINT                   NOT NULL REFERENCES monitored_services (id) ON DELETE CASCADE,
    checked_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    up               BOOLEAN                  NOT NULL,
    status_code      INTEGER,
    response_time_ms BIGINT,
    error_message    VARCHAR(500)
);

CREATE INDEX idx_checks_service_time ON health_checks (service_id, checked_at DESC);
